/**
 * "Before downloading" sheet: audio or video, automatic or custom format, and extras.
 * Choosing "Özel" opens [FormatSelectionScreen] to pick the exact audio and video streams.
 */
@OptIn(ExperimentalMaterial3Api::class, ExperimentalLayoutApi::class)
@Composable
fun FormatPickerBottomSheet(
    url: String,
    mediaInfo: MediaInfo?, // only fetched once "Biçimleri seç" asks for the format list
    error: String?,
    onLoadFormats: () -> Unit,
    onDismiss: () -> Unit,
    onStartDownload: (DownloadOptions) -> Unit
) {
    val sheetState = rememberModalBottomSheetState(skipPartiallyExpanded = true)
    var isAudio by rememberSaveable { mutableStateOf(false) }
    var custom by rememberSaveable { mutableStateOf(false) }
    var preferCompatible by rememberSaveable { mutableStateOf(true) }
    var audioTarget by rememberSaveable { mutableStateOf("mp3") }

    var playlist by rememberSaveable { mutableStateOf(false) }
    var subtitles by rememberSaveable { mutableStateOf(false) }
    var subtitleLang by rememberSaveable { mutableStateOf(mediaInfo?.subtitles?.firstOrNull()?.languageCode ?: "tr") }
    var saveThumbnail by rememberSaveable { mutableStateOf(false) }

    var showFormatScreen by remember { mutableStateOf(false) }
    // "Biçimleri seç" was pressed and the format list is being fetched
    var formatsRequested by remember { mutableStateOf(false) }
    val waitingForFormats = formatsRequested && mediaInfo == null && error == null

    // Open the format list as soon as the requested details arrive
    LaunchedEffect(mediaInfo) {
        if (mediaInfo == null) return@LaunchedEffect
        if (formatsRequested) {
            formatsRequested = false
            showFormatScreen = true
        }
    }

    val compatible = remember(mediaInfo) { mediaInfo?.let(::compatiblePair) }
    val bestQuality = remember(mediaInfo) { mediaInfo?.let(::bestQualityPair) }
    // Subtitles are embedded into the video, so they only apply to video downloads
    val canEmbedSubtitles = !isAudio
    // Without fetched details the common languages are offered; yt-dlp falls back to captions
    val subtitleChoices = mediaInfo?.subtitles?.takeIf { it.isNotEmpty() }
        ?.map { it.languageCode to subtitleLabel(it.languageName, it.isAutoGenerated) }
        ?: listOf("tr" to "Türkçe", "en" to "English")

    // Extras from this sheet apply to both automatic and custom downloads
    fun withExtras(options: DownloadOptions) = options.copy(
        downloadPlaylist = playlist,
        saveThumbnail = saveThumbnail
    )

    fun automaticOptions(): DownloadOptions = if (isAudio) {
        DownloadOptions(
            isAudioOnly = true,
            audioFormat = audioTarget,
            ext = audioTarget,
            label = audioTarget.uppercase()
        )
    } else {
        val pair = if (preferCompatible) compatible else bestQuality
        DownloadOptions(
            isAudioOnly = false,
            preferCompatible = preferCompatible,
            ext = "mp4",
            label = pair?.video?.height?.let { "${it}p" },
            embedSubtitles = subtitles && canEmbedSubtitles && subtitleLang != null,
            subtitleLang = subtitleLang
        )
    }

    if (showFormatScreen && mediaInfo != null) {
        FormatSelectionScreen(
            mediaInfo = mediaInfo,
            audioOnly = isAudio,
            initialSubtitleLang = if (subtitles) subtitleLang else null,
            // Closing the format list (X or back) cancels the whole download
            onClose = {
                showFormatScreen = false
                onDismiss()
            },
            onConfirm = { options ->
                showFormatScreen = false
                onStartDownload(withExtras(options))
            }
        )
    }

    ModalBottomSheet(
        onDismissRequest = onDismiss,
        sheetState = sheetState,
        shape = RoundedCornerShape(topStart = 12.dp, topEnd = 12.dp),
        containerColor = MaterialTheme.colorScheme.surfaceContainerLow
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .verticalScroll(rememberScrollState())
                .padding(horizontal = 20.dp)
                .padding(bottom = 24.dp)
        ) {
            Text(text = "İndirmeden önce", style = MaterialTheme.typography.headlineSmall)
            Text(
                text = mediaInfo?.title ?: url,
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                maxLines = 2
            )

            SectionLabel("İndirme türü")
            SegmentedRow(
                options = listOf(
                    Segment(true, "Ses", Icons.Outlined.MusicNote),
                    Segment(false, "Video", Icons.Outlined.Videocam)
                ),
                selected = isAudio,
                onSelect = { isAudio = it }
            )

            SectionLabel("Biçim seçimi")
            SegmentedRow(
                options = listOf(Segment(false, "Otomatik"), Segment(true, "Özel")),
                selected = custom,
                onSelect = { custom = it }
            )

            if (custom) {
                Hint("Devam ettiğinizde ses ve görüntü biçimlerini tek tek seçebileceğiniz liste açılır.")
            } else {
                SectionLabel("Biçim tercihi")
                if (isAudio) {
                    SegmentedRow(
                        options = listOf(Segment("mp3", "MP3"), Segment("m4a", "M4A"), Segment("opus", "Opus")),
                        selected = audioTarget,
                        onSelect = { audioTarget = it }
                    )
                    val (description, size) = when (audioTarget) {
                        "m4a" -> "AAC ses, yeniden kodlanmadan kaydedilir." to mediaInfo?.let { bestAudio(it, ext = "m4a") }?.fileSizeApprox
                        "opus" -> "En verimli ses, yeniden kodlanmadan kaydedilir. Bazı eski cihazlar oynatmayabilir." to
                            mediaInfo?.let { bestAudio(it, codec = "opus") }?.fileSizeApprox
                        // yt-dlp's best-quality MP3 (VBR -q 0) averages about 245 kbps
                        else -> "Her cihazda çalışır, en iyi sesten dönüştürülür." to
                            mediaInfo?.durationSeconds?.takeIf { it > 0 }?.let { it * 245_000L / 8 }
                    }
                    Hint(withSize(description, size))
                } else {
                    SegmentedRow(
                        options = listOf(Segment(true, "Uyumlu"), Segment(false, "En iyi kalite")),
                        selected = preferCompatible,
                        onSelect = { preferCompatible = it }
                    )
                    val pair = if (preferCompatible) compatible else bestQuality
                    val resolution = pair?.video?.height?.let { "${it}p" }
                    val description = if (preferCompatible) {
                        "H.264 ve AAC, MP4. Her telefonda ve televizyonda oynatılır."
                    } else {
                        "En yüksek çözünürlük; VP9 veya AV1 olabilir, eski cihazlar oynatmayabilir."
                    }
                    val details = listOfNotNull(resolution, formatSize(pair?.sizeBytes)?.let { "tahmini boyut $it" })
                    Hint(if (details.isEmpty()) description else "$description ${details.joinToString(", ")}.")
                }
            }

            SectionLabel("Ek ayarlar")
            FlowRow(
                horizontalArrangement = Arrangement.spacedBy(8.dp),
                verticalArrangement = Arrangement.spacedBy(8.dp)
            ) {
                ToggleChip("Oynatma listesini indir", playlist) { playlist = it }
                if (canEmbedSubtitles) ToggleChip("Altyazıları indir", subtitles) { subtitles = it }
                ToggleChip("Küçük resmi kaydet", saveThumbnail) { saveThumbnail = it }
            }
            val extrasHint = listOfNotNull(
                "Bağlantı bir oynatma listesindeyse listedeki tüm videolar ayrı bir klasöre indirilir.".takeIf { playlist },
                "Altyazı videoya gömülür.".takeIf { subtitles && canEmbedSubtitles },
                "Küçük resim JPG olarak Pictures/Neko klasörüne (özel kaydetme klasörü seçtiyseniz oraya) kaydedilir.".takeIf { saveThumbnail }
            )
            if (extrasHint.isNotEmpty()) Hint(extrasHint.joinToString(" "))

            // In custom mode the language is picked on the format screen
            if (subtitles && canEmbedSubtitles && !custom) {
                SectionLabel("Altyazı dili")
                Row(
                    horizontalArrangement = Arrangement.spacedBy(8.dp),
                    modifier = Modifier.horizontalScroll(rememberScrollState())
                ) {
                    subtitleChoices.forEach { (code, label) ->
                        ToggleChip(label, subtitleLang == code) { subtitleLang = code }
                    }
                }
            }

            Spacer(modifier = Modifier.height(24.dp))

            if (waitingForFormats) {
                LinearProgressIndicator(
                    color = MaterialTheme.colorScheme.onSurface,
                    trackColor = MaterialTheme.colorScheme.onSurface.copy(alpha = 0.15f),
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(bottom = 16.dp)
                )
            } else if (formatsRequested && error != null) {
                Text(
                    text = "Biçimler alınamadı: $error",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.error,
                    modifier = Modifier.padding(bottom = 16.dp)
                )
            }

            Row(horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                OutlinedButton(
                    onClick = onDismiss,
                    shape = MaterialTheme.shapes.small,
                    modifier = Modifier
                        .weight(1f)
                        .height(52.dp)
                ) {
                    Text("İptal", color = MaterialTheme.colorScheme.onSurface)
                }
                Button(
                    onClick = {
                        when {
                            !custom -> onStartDownload(withExtras(automaticOptions()))
                            mediaInfo != null -> showFormatScreen = true
                            else -> {
                                // Only now fetch the formats; the list opens when they arrive
                                formatsRequested = true
                                onLoadFormats()
                            }
                        }
                    },
                    enabled = !waitingForFormats,
                    shape = MaterialTheme.shapes.small,
                    colors = ButtonDefaults.buttonColors(
                        containerColor = MaterialTheme.colorScheme.primary,
                        contentColor = MaterialTheme.colorScheme.onPrimary
                    ),
                    modifier = Modifier
                        .weight(1f)
                        .height(52.dp)
                ) {
                    Text(
                        text = if (custom) "Biçimleri seç" else "İndir",
                        fontWeight = FontWeight.SemiBold
                    )
                }
            }
        }
    }
}

internal fun subtitleLabel(name: String, auto: Boolean) = if (auto) "$name (otomatik)" else name

private fun withSize(text: String, size: Long?) =
    formatSize(size)?.let { "$text Tahmini boyut: $it." } ?: text

@Composable
private fun SectionLabel(text: String) {
    Text(
        text = text,
        style = MaterialTheme.typography.titleSmall,
        fontWeight = FontWeight.SemiBold,
        modifier = Modifier.padding(top = 20.dp, bottom = 8.dp)
    )
}

@Composable
private fun Hint(text: String) {
    Text(
        text = text,
        style = MaterialTheme.typography.bodySmall,
        color = MaterialTheme.colorScheme.onSurfaceVariant,
        modifier = Modifier.padding(top = 8.dp)
    )
}

