package com.sahinkaya.neko.model

import kotlinx.serialization.Serializable
import java.util.UUID

enum class MediaPlatform(val displayName: String) {
    YOUTUBE("YouTube"),
    INSTAGRAM("Instagram"),
    TIKTOK("TikTok"),
    TWITTER("X (Twitter)"),
    FACEBOOK("Facebook"),
    VIMEO("Vimeo"),
    REDDIT("Reddit"),
    OTHER("Web");

    companion object {
        fun fromUrl(url: String): MediaPlatform {
            val lower = url.lowercase()
            return when {
                lower.contains("youtube.com") || lower.contains("youtu.be") -> YOUTUBE
                lower.contains("instagram.com") -> INSTAGRAM
                lower.contains("tiktok.com") -> TIKTOK
                lower.contains("twitter.com") || lower.contains("x.com") -> TWITTER
                lower.contains("facebook.com") || lower.contains("fb.watch") -> FACEBOOK
                lower.contains("vimeo.com") -> VIMEO
                lower.contains("reddit.com") -> REDDIT
                else -> OTHER
            }
        }
    }
}

@Serializable
data class SubtitleOption(
    val languageCode: String,
    val languageName: String,
    val ext: String = "vtt",
    val isAutoGenerated: Boolean = false
)

@Serializable
data class FormatOption(
    val formatId: String,
    val ext: String,
    val resolution: String? = null,
    val height: Int? = null,
    val fps: Int? = null,
    val vcodec: String? = null,
    val acodec: String? = null,
    val fileSizeApprox: Long? = null, // in bytes
    val bitrateKbps: Int? = null, // total bitrate (tbr), used to estimate size when yt-dlp gives none
    val formatNote: String? = null, // yt-dlp label such as "medium" or "1080p"
    val width: Int? = null,
    val isHls: Boolean = false, // m3u8 copy of a stream; yt-dlp prefers the plain https one
    val isAudioOnly: Boolean = false,
    val isVideoOnly: Boolean = false
) {
    val displayTitle: String
        get() {
            return when {
                isAudioOnly -> "Ses: ${ext.uppercase()} (${acodec ?: "standart"})"
                height != null -> "${height}p${if (fps != null && fps > 30) " $fps" else ""} ($ext)"
                resolution != null -> "$resolution ($ext)"
                else -> ext.uppercase()
            }
        }
}

data class MediaInfo(
    val url: String,
    val id: String,
    val title: String,
    val thumbnailUrl: String? = null,
    val uploader: String? = null,
    val durationSeconds: Long? = null,
    val formats: List<FormatOption> = emptyList(),
    val subtitles: List<SubtitleOption> = emptyList(),
    val isPlaylist: Boolean = false,
    val playlistCount: Int? = null,
    val platform: MediaPlatform = MediaPlatform.fromUrl(url)
)

enum class DownloadPreset {
    BEST_VIDEO_AUDIO,   // Best quality video + audio combined
    AUDIO_MP3,          // Extracted to MP3
    AUDIO_M4A,          // Native AAC/M4A
    CUSTOM_RESOLUTION   // Specific resolution picked by user
}

@Serializable
enum class DownloadStatus {
    QUEUED,
    INITIALIZING,
    DOWNLOADING,
    PROCESSING_FFMPEG,
    PAUSED,
    COMPLETED,
    ERROR,
    CANCELLED
}

@Serializable
data class DownloadItem(
    val id: String = UUID.randomUUID().toString(),
    val url: String,
    val title: String,
    val thumbnailUrl: String? = null,
    val platform: String = "Web",
    val formatId: String = "best",
    val ext: String = "mp4",
    val isAudioOnly: Boolean = false,
    val audioFormat: String? = null,
    val targetResolution: String? = null,
    val startTimeSeconds: String? = null,
    val endTimeSeconds: String? = null,
    val embedSubtitles: Boolean = false,
    val selectedSubtitleLang: String? = null,
    val embedThumbnail: Boolean = true,
    // Automatic video choice: H.264/AAC MP4 instead of the highest-quality codecs
    val preferCompatible: Boolean = true,
    val downloadPlaylist: Boolean = false,
    val saveThumbnail: Boolean = false, // keep the thumbnail as a JPG next to the media
    val progress: Float = 0f, // 0..100
    val speed: String = "",
    val eta: String = "",
    val downloadedBytes: Long = 0L,
    val totalBytes: Long = 0L,
    val status: DownloadStatus = DownloadStatus.QUEUED,
    val errorMessage: String? = null,
    val localFilePath: String? = null,
    val createdAt: Long = System.currentTimeMillis()
)

/** What the user chose in the download sheet; the view model turns it into a DownloadItem. */
data class DownloadOptions(
    val isAudioOnly: Boolean,
    val formatSelector: String = "best", // yt-dlp -f value, or "best" for the automatic choice
    val audioFormat: String? = null, // target for audio downloads: mp3, m4a, opus or best (keep as is)
    val preferCompatible: Boolean = true,
    val ext: String = "mp4",
    val label: String? = null, // e.g. "1080p", kept as targetResolution
    val embedSubtitles: Boolean = false,
    val subtitleLang: String? = null,
    val embedThumbnail: Boolean = true,
    val downloadPlaylist: Boolean = false,
    val saveThumbnail: Boolean = false,
    val startTime: String? = null,
    val endTime: String? = null
)
